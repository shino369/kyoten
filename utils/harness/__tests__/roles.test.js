import fs from 'fs';
import os from 'os';
import path from 'path';
import { ROOT_DIR } from '#utils/workspace-config.js';
import {
  agyRoleFiles,
  agyTools,
  codexRoleFiles,
  parseRole,
  renderAgyRole,
  renderCodexRole,
} from '../roles.js';

const REVIEWER = `---
name: reviewer
description: Clean-context reviewer. Works from the "BRIEF" file.
model: sonnet
tools: Read, Grep, Glob, Edit
---

# Reviewer

Follow the brief. Paths look like C:\\\\work and quotes like """ stay.
`;

describe('parseRole', () => {
  test('should read the frontmatter and the body', () => {
    expect(parseRole(REVIEWER, 'reviewer.md')).toEqual({
      name: 'reviewer',
      description: 'Clean-context reviewer. Works from the "BRIEF" file.',
      model: 'sonnet',
      tools: ['Read', 'Grep', 'Glob', 'Edit'],
      body: '# Reviewer\n\nFollow the brief. Paths look like C:\\\\work and quotes like """ stay.\n',
    });
  });

  test('should fall back to the file name, and to all tools without a tools line', () => {
    expect(
      parseRole('---\ndescription: D\n  - a list item\n---\nBody', 'planner.md')
    ).toEqual({
      name: 'planner',
      description: 'D',
      tools: null,
      body: 'Body',
    });
  });

  test('should return null for a file without frontmatter or a description', () => {
    expect(parseRole('# Just markdown', 'x.md')).toBeNull();
    expect(parseRole('---\nname: x\n---\nBody', 'x.md')).toBeNull();
  });
});

describe('renderCodexRole', () => {
  test('should write a Codex role file that can write when the role can', () => {
    const text = renderCodexRole(
      /** @type {import('../roles.js').Role} */ (
        parseRole(REVIEWER, 'reviewer.md')
      ),
      '.claude/agents/reviewer.md'
    );
    expect(text).toBe(
      [
        '# Generated by pnpm harness sync from .claude/agents/reviewer.md; do not edit.',
        'name = "reviewer"',
        'description = "Clean-context reviewer. Works from the \\"BRIEF\\" file."',
        'sandbox_mode = "workspace-write"',
        'model_reasoning_effort = "medium"',
        'developer_instructions = """',
        '# Reviewer',
        '',
        'Follow the brief. Paths look like C:\\\\\\\\work and quotes like ""\\" stay.',
        '"""',
        '',
      ].join('\n')
    );
  });

  test('should make a role read-only when it can only read', () => {
    const role = /** @type {import('../roles.js').Role} */ (
      parseRole(
        '---\nname: security-reviewer\ndescription: D\ntools: Read, Grep, Glob\n---\nB',
        'x.md'
      )
    );
    expect(renderCodexRole(role, 'x.md')).toContain(
      'sandbox_mode = "read-only"'
    );
  });

  test('should let a role with every tool write', () => {
    const role = /** @type {import('../roles.js').Role} */ (
      parseRole('---\nname: t\ndescription: D\n---\nB', 't.md')
    );
    expect(renderCodexRole(role, 't.md')).toContain(
      'sandbox_mode = "workspace-write"'
    );
  });
});

describe('agyTools', () => {
  const roleOf = (/** @type {string} */ tools) =>
    /** @type {import('../roles.js').Role} */ (
      parseRole(`---\nname: r\ndescription: D\n${tools}---\nB`, 'r.md')
    );

  test('should map Claude tools to the verified agy CLI names, dropping Grep and Glob', () => {
    expect(agyTools(roleOf('tools: Read, Grep, Glob, Bash, Edit\n'))).toEqual([
      'read_file',
      'edit_file',
      'run_command',
    ]);
  });

  test('should give every agy tool to a role with no tools line', () => {
    expect(agyTools(roleOf(''))).toEqual([
      'read_file',
      'write_file',
      'edit_file',
      'run_command',
    ]);
  });

  test('should keep only read_file for a read-only role and nothing for unmapped tools', () => {
    expect(agyTools(roleOf('tools: Read, Grep, Glob\n'))).toEqual([
      'read_file',
    ]);
    expect(agyTools(roleOf('tools: Grep, Glob\n'))).toEqual([]);
  });
});

describe('renderAgyRole and agyRoleFiles', () => {
  test('should let the Antigravity reviewer edit without running commands', () => {
    const reviewer = /** @type {import('../roles.js').Role} */ (
      parseRole(REVIEWER, 'reviewer.md')
    );
    const rendered = renderAgyRole(reviewer, '.claude/agents/reviewer.md');
    expect(rendered).toContain('name: reviewer\n');
    expect(rendered).toContain(
      'description: \'Clean-context reviewer. Works from the "BRIEF" file.\'\n'
    );
    expect(rendered).toContain(
      'subagent: true\nmainAgent: false\nmodel: flash\n'
    );
    expect(rendered).toContain('tools:\n  - read_file\n  - edit_file\n');
    expect(rendered).not.toContain('run_command');
    expect(rendered).toContain('commandExecutionPolicy: off\n');
    expect(rendered).toContain(
      '<!-- Generated by pnpm harness sync from .claude/agents/reviewer.md; do not edit. -->'
    );
  });

  test('should disable commands for a read-only Antigravity role', () => {
    const readOnly = /** @type {import('../roles.js').Role} */ (
      parseRole(
        "---\nname: security-reviewer\ndescription: Don't miss secrets.\ntools: Read, Grep, Glob\n---\nB",
        'security-reviewer.md'
      )
    );
    const renderedReadOnly = renderAgyRole(readOnly, 'x.md');
    expect(renderedReadOnly).toContain('description: "Don\'t miss secrets."\n');
    expect(renderedReadOnly).toContain('tools:\n  - read_file\n');
    expect(renderedReadOnly).toContain('commandExecutionPolicy: off\n');
  });

  test('should give a role without a tools line every verified agy tool', () => {
    const all = /** @type {import('../roles.js').Role} */ (
      parseRole('---\nname: t\ndescription: D\n---\nB', 't.md')
    );

    expect(renderAgyRole(all, 't.md')).toContain(
      'tools:\n  - read_file\n  - write_file\n  - edit_file\n  - run_command\n'
    );
  });

  test('should omit the tools block when no Claude tool maps', () => {
    const none = /** @type {import('../roles.js').Role} */ (
      parseRole(
        '---\nname: g\ndescription: D\ntools: Grep, Glob\n---\nB',
        'g.md'
      )
    );

    expect(renderAgyRole(none, 'g.md')).not.toContain('tools:');
  });

  test('should ignore trailing commas in tools and parse optional skills', () => {
    const role = /** @type {import('../roles.js').Role} */ (
      parseRole(
        '---\nname: t\ndescription: D\ntools: Read, Grep, \nskills: translation-expertise, skills/custom\n---\nB',
        't.md'
      )
    );
    expect(role.tools).toEqual(['Read', 'Grep']);
    expect(role.skills).toEqual(['translation-expertise', 'skills/custom']);
    const rendered = renderAgyRole(role, 't.md');
    expect(rendered).toContain('tools:\n  - read_file\n');
    expect(rendered).toContain(
      'skills:\n  - skills/translation-expertise\n  - skills/custom\n'
    );
    expect(rendered).toContain('commandExecutionPolicy: off\n');
  });

  test('should generate one Antigravity role per Claude agent file in the workspace', () => {
    const files = agyRoleFiles(ROOT_DIR);
    const names = fs
      .readdirSync(path.join(ROOT_DIR, '.claude/agents'))
      .filter((f) => f.endsWith('.md'))
      .map((f) => `.agents/agents/${f}`);
    expect(files.map((f) => f.file).sort()).toEqual(names.sort());
    expect(
      files.find((f) => f.file.endsWith('/security-reviewer.md'))?.content
    ).toContain('commandExecutionPolicy: off');
  });
});

describe('cross-harness role model tiers', () => {
  test.each([
    ['haiku', 'flash', 'low'],
    ['sonnet', 'flash', 'medium'],
    ['opus', 'pro', 'high'],
    ['inherit', 'inherit', null],
    ['unknown', 'inherit', null],
    ['constructor', 'inherit', null],
    ['', 'inherit', null],
  ])('should render Claude model %s for each harness', (model, agy, effort) => {
    const frontmatter = model ? `model: ${model}\n` : '';
    const role = /** @type {import('../roles.js').Role} */ (
      parseRole(`---\ndescription: D\n${frontmatter}---\nBody`, 'agent.md')
    );

    expect(renderAgyRole(role, 'agent.md')).toContain(`model: ${agy}\n`);
    const codex = renderCodexRole(role, 'agent.md');
    if (effort) {
      expect(codex).toContain(`model_reasoning_effort = "${effort}"\n`);
    } else {
      expect(codex).not.toContain('model_reasoning_effort');
    }
    expect(codex).not.toMatch(/^model\s*=/m);
  });

  test.each([
    ['planner', 'sonnet', 'medium'],
    ['reviewer', 'sonnet', 'medium'],
    ['security-reviewer', 'sonnet', 'medium'],
    ['test-runner', 'haiku', 'low'],
    ['trilingual-translator', 'sonnet', 'medium'],
    ['verifier', 'sonnet', 'medium'],
  ])('should ship the configured tier for %s', (name, model, effort) => {
    const source = `.claude/agents/${name}.md`;
    const role = parseRole(
      fs.readFileSync(path.join(ROOT_DIR, source), 'utf-8'),
      source
    );

    expect(role?.model).toBe(model);
    expect(
      agyRoleFiles(ROOT_DIR).find(
        ({ file }) => file === `.agents/agents/${name}.md`
      )?.content
    ).toContain('model: flash\n');
    expect(
      codexRoleFiles(ROOT_DIR).find(
        ({ file }) => file === `.codex/agents/${name}.toml`
      )?.content
    ).toContain(`model_reasoning_effort = "${effort}"\n`);
  });
});

describe('codexRoleFiles', () => {
  test('should generate one Codex role per Claude agent file in the workspace', () => {
    const files = codexRoleFiles(ROOT_DIR);
    const names = fs
      .readdirSync(path.join(ROOT_DIR, '.claude/agents'))
      .filter((f) => f.endsWith('.md'))
      .map((f) => `.codex/agents/${f.replace(/\.md$/, '.toml')}`);
    expect(files.map((f) => f.file).sort()).toEqual(names.sort());
    expect(
      files.find((f) => f.file.endsWith('/reviewer.toml'))?.content
    ).toContain('name = "reviewer"');
  });

  test('should return nothing without an agents folder', () => {
    expect(codexRoleFiles(path.join(ROOT_DIR, 'no-such-dir'))).toEqual([]);
  });

  test('should skip files that are not roles', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'roles-'));
    const dir = path.join(root, '.claude/agents');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(
      path.join(dir, 'a.md'),
      '---\nname: a\ndescription: D\n---\nB'
    );
    fs.writeFileSync(path.join(dir, 'notes.md'), '# not a role');
    fs.writeFileSync(path.join(dir, 'b.txt'), 'x');
    expect(codexRoleFiles(root).map((f) => f.file)).toEqual([
      '.codex/agents/a.toml',
    ]);
    fs.rmSync(root, { recursive: true, force: true });
  });
});
