/**
 * The workspace's roles (`.claude/agents/<role>.md`, Claude Code subagents)
 * rendered for other harnesses:
 * - Codex: `.codex/agents/<role>.toml` (`spawn_agent` with `agent_type`)
 * - Antigravity CLI: `.agents/agents/<role>.md` (`invoke_subagent` with `TypeName`)
 *
 * `pnpm harness sync` writes them; `.claude/agents/*.md` stays the source.
 *
 * - Claude model aliases map to Antigravity tiers and Codex reasoning effort.
 * - Codex uses a read-only sandbox for roles whose tools are only Read, Grep,
 *   and Glob. Antigravity disables command execution for roles without Bash.
 *
 * DSH has no role files: its `subagent` tool is told to follow the markdown.
 */
import fs from 'fs';
import path from 'path';

const AGENTS_DIR = '.claude/agents';
const READ_ONLY_TOOLS = new Set(['Read', 'Grep', 'Glob']);
const FRONTMATTER_RE = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;

/**
 * @typedef {{ name: string, description: string, tools: string[] | null, model?: string, skills?: string[], body: string }} Role
 *   tools: null when the role gets every tool
 */

/**
 * A role file's frontmatter (simple `key: value` lines) and body, or null
 * when it has no frontmatter or no description.
 *
 * @param {string} text
 * @param {string} fileName
 * @returns {Role | null}
 */
export function parseRole(text, fileName) {
  const match = FRONTMATTER_RE.exec(text);
  if (!match) return null;
  /** @type {Record<string, string>} */
  const fields = {};
  for (const line of match[1].split(/\r?\n/)) {
    const colon = line.indexOf(':');
    if (colon > 0)
      fields[line.slice(0, colon).trim()] = line.slice(colon + 1).trim();
  }
  if (!fields.description) return null;
  const skills = fields.skills
    ? fields.skills.split(/\s*,\s*/).filter(Boolean)
    : [];
  return {
    name: fields.name || path.basename(fileName, '.md'),
    description: fields.description,
    tools: fields.tools ? fields.tools.split(/\s*,\s*/).filter(Boolean) : null,
    ...(fields.model ? { model: fields.model } : {}),
    ...(skills.length > 0 ? { skills } : {}),
    body: text.slice(match[0].length).replace(/^\r?\n/, ''),
  };
}

/** @param {Role} role */
export function agyModel(role) {
  switch (role.model) {
    case 'haiku':
    case 'sonnet':
      return 'flash';
    case 'opus':
      return 'pro';
    default:
      return 'inherit';
  }
}

/** @param {Role} role */
export function codexReasoningEffort(role) {
  switch (role.model) {
    case 'haiku':
      return 'low';
    case 'sonnet':
      return 'medium';
    case 'opus':
      return 'high';
    default:
      return null;
  }
}

/** @param {Role} role */
const isReadOnly = (role) =>
  role.tools !== null && role.tools.every((tool) => READ_ONLY_TOOLS.has(tool));

/**
 * Claude Code tool names mapped to the names declared by the Antigravity CLI.
 * Only verified CLI names are emitted: an IDE/App-only name (`view_file`,
 * `grep_search`, …) can hang the subagent. Grep and Glob have no verified CLI
 * equivalent; `run_command` covers them wherever Bash is present, and
 * reviewers read the pre-computed `DIFF_*.patch`.
 */
/** @type {Record<string, string>} */
const AGY_TOOL_NAMES = {
  Read: 'read_file',
  Write: 'write_file',
  Edit: 'edit_file',
  Bash: 'run_command',
};
/** Every `agy` tool a role can receive, in output order. */
const AGY_ALL_TOOLS = ['read_file', 'write_file', 'edit_file', 'run_command'];

/**
 * The Antigravity `tools:` for a role: the mapped names in a fixed order
 * (all of them when the role has no `tools` line).
 *
 * @param {Role} role
 * @returns {string[]}
 */
export function agyTools(role) {
  if (role.tools === null) return [...AGY_ALL_TOOLS];
  const mapped = new Set(
    role.tools.map((tool) => AGY_TOOL_NAMES[tool]).filter(Boolean)
  );
  return AGY_ALL_TOOLS.filter((name) => mapped.has(name));
}

/** @param {string} text a TOML multi-line basic string's content */
const multiline = (text) =>
  text.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"');

/**
 * @param {Role} role
 * @param {string} source the markdown file, for the header
 * @returns {string} the Codex role file
 */
export function renderCodexRole(role, source) {
  const effort = codexReasoningEffort(role);
  return [
    `# Generated by pnpm harness sync from ${source}; do not edit.`,
    `name = ${JSON.stringify(role.name)}`,
    `description = ${JSON.stringify(role.description)}`,
    `sandbox_mode = "${isReadOnly(role) ? 'read-only' : 'workspace-write'}"`,
    ...(effort ? [`model_reasoning_effort = "${effort}"`] : []),
    'developer_instructions = """',
    `${multiline(role.body.replace(/\n+$/, ''))}`,
    '"""',
    '',
  ].join('\n');
}

/** @param {string} value YAML string matching this workspace's Prettier style */
const yamlString = (value) =>
  value.includes("'") || /[\n\r\t\\]/.test(value)
    ? JSON.stringify(value)
    : `'${value}'`;

/**
 * Render an Antigravity custom subagent file (`.agents/agents/<role>.md`).
 * Targets Antigravity CLI (`agy`): `tools:` carries only the verified CLI
 * names (App/IDE names such as `view_file` can hang the CLI subagent, and
 * vice versa); `mainAgent: false` keeps subagent roles out of `/agents`'s
 * primary-agent switcher while exposing them to `invoke_subagent`. A role
 * whose tools all lack a CLI equivalent gets no `tools:` block. Roles
 * without `run_command` disable shell commands via `commandExecutionPolicy: off`.
 *
 * @param {Role} role
 * @param {string} source the markdown file, for the header comment
 * @returns {string}
 */
export function renderAgyRole(role, source) {
  const tools = agyTools(role);
  const skills = role.skills ?? [];
  return [
    '---',
    `name: ${role.name}`,
    `description: ${yamlString(role.description)}`,
    'subagent: true',
    'mainAgent: false',
    `model: ${agyModel(role)}`,
    ...(tools.length > 0
      ? ['tools:', ...tools.map((tool) => `  - ${tool}`)]
      : []),
    ...(skills.length > 0
      ? [
          'skills:',
          ...skills.map((skill) =>
            skill.includes('/') ? `  - ${skill}` : `  - skills/${skill}`
          ),
        ]
      : []),
    ...(!tools.includes('run_command') ? ['commandExecutionPolicy: off'] : []),
    '---',
    '',
    `<!-- Generated by pnpm harness sync from ${source}; do not edit. -->`,
    '',
    role.body.replace(/\r?\n+$/, ''),
    '',
  ].join('\n');
}

/**
 * @param {string} rootDir
 * @returns {{ name: string, role: Role }[]}
 */
function readRoles(rootDir) {
  const dir = path.join(rootDir, AGENTS_DIR);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith('.md'))
    .sort()
    .flatMap((name) => {
      const role = parseRole(
        fs.readFileSync(path.join(dir, name), 'utf-8'),
        name
      );
      return role ? [{ name, role }] : [];
    });
}

/**
 * The Codex role files for every role in `.claude/agents/`.
 *
 * @param {string} rootDir
 * @returns {{ file: string, content: string }[]}
 */
export function codexRoleFiles(rootDir) {
  return readRoles(rootDir).map(({ name, role }) => ({
    file: `.codex/agents/${path.basename(name, '.md')}.toml`,
    content: renderCodexRole(role, `${AGENTS_DIR}/${name}`),
  }));
}

/**
 * The Antigravity subagent files for every role in `.claude/agents/`.
 *
 * @param {string} rootDir
 * @returns {{ file: string, content: string }[]}
 */
export function agyRoleFiles(rootDir) {
  return readRoles(rootDir).map(({ name, role }) => ({
    file: `.agents/agents/${name}`,
    content: renderAgyRole(role, `${AGENTS_DIR}/${name}`),
  }));
}
